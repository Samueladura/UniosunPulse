$$;
INSERT INTO positions (election_id, title)
SELECT DISTINCT election_id, btrim(position)
FROM election_candidates
WHERE position_id IS NULL AND btrim(position) <> ''
ON CONFLICT (election_id, title) DO NOTHING;
UPDATE election_candidates AS candidate
SET position_id = position_row.id
FROM positions AS position_row
WHERE candidate.position_id IS NULL
  AND position_row.election_id = candidate.election_id
  AND position_row.title = btrim(candidate.position);
