CREATE OR REPLACE FUNCTION cast_vote(
  p_election_id uuid,
  p_position_id text,
  p_candidate_id uuid,
  p_user_id text
) RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
  v_receipt_hash text;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM elections
    WHERE id = p_election_id
      AND status = 'active'
      AND (COALESCE(start_at, start_time) IS NULL OR COALESCE(start_at, start_time) <= now())
      AND (COALESCE(end_at, end_time) IS NULL OR COALESCE(end_at, end_time) > now())
  ) THEN
    RAISE EXCEPTION 'Election is not currently accepting votes';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM election_candidates
    WHERE id = p_candidate_id
      AND election_id = p_election_id
      AND position_id = p_position_id
  ) THEN
    RAISE EXCEPTION 'Candidate does not belong to this election position';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM positions
    WHERE id = p_position_id
      AND election_id = p_election_id
  ) THEN
    RAISE EXCEPTION 'Position does not belong to this election';
  END IF;

  v_receipt_hash := 'BAL-' || encode(gen_random_bytes(3), 'hex')
    || '-' || encode(gen_random_bytes(4), 'hex');

  INSERT INTO election_votes (
    election_id, voter_id, candidate_id, position_id, receipt_hash
  ) VALUES (
    p_election_id, p_user_id, p_candidate_id, p_position_id, v_receipt_hash
  )
  ON CONFLICT (election_id, voter_id, position_id) DO NOTHING
  RETURNING receipt_hash INTO v_receipt_hash;

  IF NOT FOUND THEN
    SELECT receipt_hash INTO v_receipt_hash
    FROM election_votes
    WHERE election_id = p_election_id
      AND voter_id = p_user_id
      AND position_id = p_position_id;
    RETURN jsonb_build_object('receipt_hash', v_receipt_hash, 'is_duplicate', true);
  END IF;

  UPDATE election_candidates
  SET vote_count = vote_count + 1
  WHERE id = p_candidate_id;

  UPDATE elections
  SET total_votes = total_votes + 1, updated_at = now()
  WHERE id = p_election_id;

  RETURN jsonb_build_object(
    'receipt_hash', v_receipt_hash,
    'is_duplicate', false
  );
END;
$$;

