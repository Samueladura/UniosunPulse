-- Go to: Supabase Dashboard > SQL Editor > Paste > Run

-- Posts table
create table if not exists public.posts (
  id text primary key default gen_random_uuid()::text,
  author_id text not null,is_broadcast boolean not null default false,
  author_name text not null,
  avatar text,
  title text not null,
  body text,
  image text,
  tag text default 'ANNOUNCEMENTS',
  like_count integer not null default 0,
  comment_count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Likes table
create table if not exists public.likes (
  id bigint generated by default as identity primary key,
  post_id text not null references public.posts(id) on delete cascade,
  user_id text not null,
  created_at timestamptz not null default now(),
  unique(post_id, user_id)
);

-- Comments table
create table if not exists public.comments (
  id text primary key default gen_random_uuid()::text,
  post_id text not null references public.posts(id) on delete cascade,
  user_id text not null,
  author_name text not null,
  avatar text,
  body text not null,
  created_at timestamptz not null default now()
);

-- Follows table
create table if not exists public.follows (
  id bigint generated by default as identity primary key,
  follower_id text not null,
  following_id text not null,
  created_at timestamptz not null default now(),
  unique(follower_id, following_id),
  check (follower_id <> following_id)
);

-- Alerts table
create table if not exists public.alerts (
  id text primary key default gen_random_uuid()::text,
  user_id text not null,
  category text not null,
  title text not null,
  body text,
  unread boolean not null default true,
  is_broadcast boolean not null default false,
  created_at timestamptz not null default now()
);

-- Indexes
create index if not exists idx_posts_created_at on public.posts(created_at desc);
create index if not exists idx_posts_tag on public.posts(tag);
create index if not exists idx_likes_post_id on public.likes(post_id);
create index if not exists idx_comments_post_id on public.comments(post_id, created_at desc);
create index if not exists idx_follows_follower on public.follows(follower_id);
create index if not exists idx_follows_following on public.follows(following_id);
create index if not exists idx_alerts_user on public.alerts(user_id, created_at desc);

-- Realtime publication
do $$
begin
  if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    create publication supabase_realtime;
  end if;
end
$$;

alter publication supabase_realtime add table if not exists public.posts;
alter publication supabase_realtime add table if not exists public.likes;
alter publication supabase_realtime add table if not exists public.comments;
alter publication supabase_realtime add table if not exists public.follows;
alter publication supabase_realtime add table if not exists public.alerts;

-- RLS Policies
do $$
begin
  if to_regclass('public.posts') is not null then
    alter table public.posts enable row level security;
    create policy "Allow all" on public.posts for all using (true) with check (true);
  end if;

  if to_regclass('public.likes') is not null then
    alter table public.likes enable row level security;
    create policy "Allow all" on public.likes for all using (true) with check (true);
  end if;

  if to_regclass('public.comments') is not null then
    alter table public.comments enable row level security;
    create policy "Allow all" on public.comments for all using (true) with check (true);
  end if;

  if to_regclass('public.follows') is not null then
    alter table public.follows enable row level security;
    create policy "Allow all" on public.follows for all using (true) with check (true);
  end if;

  if to_regclass('public.alerts') is not null then
    alter table public.alerts enable row level security;
    create policy "Allow all" on public.alerts for all using (true) with check (true);
  end if;
end
$$;
